import {
  Node,
  Project,
  SyntaxKind,
  type JsxAttribute,
  type JsxOpeningElement,
  type JsxSelfClosingElement,
  type SourceFile,
} from "ts-morph";
import {
  CodeCutError,
  applyPatches,
  assignMissingIds,
  findById,
  isNode,
  type CCNode,
  type Patch,
} from "@codecut/core";
import { printAttr, printAttrInit, printNode } from "./print.js";

type Tag = JsxOpeningElement | JsxSelfClosingElement;
type Replacement = { start: number; end: number; text: string };

const project = new Project({
  useInMemoryFileSystem: true,
  skipAddingFilesFromTsConfig: true,
  compilerOptions: { jsx: 4 /* Preserve */, allowJs: true },
});
let counter = 0;
const parse = (text: string): SourceFile =>
  project.createSourceFile(`/doc-${counter++}.tsx`, text, { overwrite: true });

const applyReplacements = (text: string, reps: Replacement[]): string => {
  let out = text;
  for (const r of [...reps].sort((a, b) => b.start - a.start))
    out = out.slice(0, r.start) + r.text + out.slice(r.end);
  return out;
};

/** True for literals the structured editor can rewrite: strings, numbers, booleans, null, arrays and plain objects of those. */
export function isStructuredExpr(node: Node | undefined): boolean {
  if (!node) return false;
  if (
    Node.isStringLiteral(node) ||
    Node.isNoSubstitutionTemplateLiteral(node) ||
    Node.isNumericLiteral(node)
  )
    return true;
  const k = node.getKind();
  if (k === SyntaxKind.TrueKeyword || k === SyntaxKind.FalseKeyword || k === SyntaxKind.NullKeyword)
    return true;
  if (Node.isPrefixUnaryExpression(node)) {
    const t = node.getOperatorToken();
    return (
      (t === SyntaxKind.MinusToken || t === SyntaxKind.PlusToken) &&
      Node.isNumericLiteral(node.getOperand())
    );
  }
  if (Node.isParenthesizedExpression(node)) return isStructuredExpr(node.getExpression());
  if (Node.isAsExpression(node)) return isStructuredExpr(node.getExpression());
  if (Node.isArrayLiteralExpression(node))
    return node.getElements().every((e) => isStructuredExpr(e));
  if (Node.isObjectLiteralExpression(node))
    return node.getProperties().every((p) => {
      if (!Node.isPropertyAssignment(p)) return false;
      const n = p.getNameNode();
      if (Node.isComputedPropertyName(n)) return false;
      return isStructuredExpr(p.getInitializer());
    });
  return false;
}

const attrStructured = (a: JsxAttribute): boolean => {
  const init = a.getInitializer();
  if (!init) return true; // bare boolean
  if (Node.isStringLiteral(init)) return true;
  if (Node.isJsxExpression(init)) return isStructuredExpr(init.getExpression());
  return false;
};

const tagIdOf = (tag: Tag): string | undefined => {
  const a = tag.getAttribute("id");
  if (!a || !Node.isJsxAttribute(a)) return undefined;
  const init = a.getInitializer();
  if (!init) return undefined;
  if (Node.isStringLiteral(init)) return init.getLiteralValue();
  if (Node.isJsxExpression(init)) {
    const e = init.getExpression();
    if (e && (Node.isStringLiteral(e) || Node.isNoSubstitutionTemplateLiteral(e)))
      return e.getLiteralValue();
  }
  return undefined;
};

const tagsOf = (sf: SourceFile): Tag[] => [
  ...sf.getDescendantsOfKind(SyntaxKind.JsxOpeningElement),
  ...sf.getDescendantsOfKind(SyntaxKind.JsxSelfClosingElement),
];

const lineIndent = (text: string, pos: number): string => {
  const ls = text.lastIndexOf("\n", pos - 1) + 1;
  return /^[ \t]*/.exec(text.slice(ls))![0];
};

/** The element a tag belongs to (JsxElement for an opening tag, itself for self-closing). */
const elementOf = (tag: Tag): Node => (Node.isJsxOpeningElement(tag) ? tag.getParent()! : tag);

interface Found {
  tag: Tag;
  el: Node;
}

/** A TSX source file edited by element id. Every method returns new source text; nothing is written to disk. */
export class TsxDoc {
  constructor(readonly text: string) {}

  private sf(): SourceFile {
    return parse(this.text);
  }

  private find(sf: SourceFile, id: string): Found {
    const tag = tagsOf(sf).find((t) => tagIdOf(t) === id);
    if (!tag)
      throw new CodeCutError(
        "opaque_expression",
        `Element #${id} is not written literally in the source file`,
        {
          fix: "It is probably generated by a function or loop. Edit the source by hand, or use scene_write on its parent.",
        },
      );
    return { tag, el: elementOf(tag) };
  }

  has(id: string): boolean {
    return tagsOf(this.sf()).some((t) => tagIdOf(t) === id);
  }

  /** Set (or with `undefined` remove) one prop. Opaque expressions are refused. */
  setProp(id: string, prop: string, value: unknown): TsxDoc {
    const sf = this.sf();
    const { tag } = this.find(sf, id);
    const attr = tag.getAttribute(prop);
    const text = this.text;
    if (attr && Node.isJsxAttribute(attr)) {
      if (!attrStructured(attr))
        throw new CodeCutError(
          "opaque_expression",
          `#${id}.${prop} is an expression (${attr.getInitializer()?.getText().slice(0, 40)}…) that structured edits cannot change`,
          { fix: "Edit it by hand, or rewrite the element with scene_write." },
        );
      if (value === undefined) {
        return new TsxDoc(
          applyReplacements(text, [{ start: attr.getPos(), end: attr.getEnd(), text: "" }]),
        );
      }
      const indent = lineIndent(text, attr.getStart());
      const nameEnd = attr.getNameNode().getEnd();
      return new TsxDoc(
        applyReplacements(text, [
          { start: nameEnd, end: attr.getEnd(), text: printAttrInit(value, indent) },
        ]),
      );
    }
    if (value === undefined) return this; // nothing to remove
    if (attr) {
      throw new CodeCutError("opaque_expression", `#${id}.${prop} comes from a spread`);
    }
    const attrs = tag.getAttributes();
    const last = attrs[attrs.length - 1];
    if (!last) {
      const nameEnd = tag.getTagNameNode().getEnd();
      return new TsxDoc(
        applyReplacements(text, [
          { start: nameEnd, end: nameEnd, text: " " + printAttr(prop, value, "") },
        ]),
      );
    }
    const multiline = tag.getStartLineNumber() !== last.getStartLineNumber();
    const indent = multiline ? lineIndent(text, last.getStart()) : lineIndent(text, tag.getStart());
    const ins = multiline
      ? `\n${indent}${printAttr(prop, value, indent)}`
      : ` ${printAttr(prop, value, indent)}`;
    return new TsxDoc(applyReplacements(text, [{ start: last.getEnd(), end: last.getEnd(), text: ins }]));
  }

  /** Read a literal prop value back from the source (undefined when absent or opaque). */
  readsLiterally(id: string, prop: string): boolean {
    const { tag } = this.find(this.sf(), id);
    const a = tag.getAttribute(prop);
    return !a || (Node.isJsxAttribute(a) && attrStructured(a));
  }

  /** Insert `node` as a child of `parentId`, before the child with id `beforeId` (or after `afterId`, or last). */
  insert(parentId: string, node: CCNode, anchor: { before?: string; after?: string }): TsxDoc {
    const sf = this.sf();
    const text = this.text;
    const { el } = this.find(sf, parentId);
    const find = (id?: string) =>
      id ? tagsOf(sf).find((t) => tagIdOf(t) === id) : undefined;
    const before = find(anchor.before);
    const after = find(anchor.after);
    if (before) {
      const e = elementOf(before);
      const indent = lineIndent(text, e.getStart());
      return new TsxDoc(
        applyReplacements(text, [
          { start: e.getStart(), end: e.getStart(), text: `${printNode(node, indent)}\n${indent}` },
        ]),
      );
    }
    if (after) {
      const e = elementOf(after);
      const indent = lineIndent(text, e.getStart());
      return new TsxDoc(
        applyReplacements(text, [
          { start: e.getEnd(), end: e.getEnd(), text: `\n${indent}${printNode(node, indent)}` },
        ]),
      );
    }
    const parentIndent = lineIndent(text, el.getStart());
    const indent = parentIndent + "  ";
    if (Node.isJsxSelfClosingElement(el)) {
      const close = `</${el.getTagNameNode().getText()}>`;
      const tagText = el.getText();
      const open = tagText.replace(/\s*\/>$/, ">");
      return new TsxDoc(
        applyReplacements(text, [
          {
            start: el.getStart(),
            end: el.getEnd(),
            text: `${open}\n${indent}${printNode(node, indent)}\n${parentIndent}${close}`,
          },
        ]),
      );
    }
    if (!Node.isJsxElement(el)) throw new CodeCutError("invalid_edit", `Cannot insert into #${parentId}`);
    const kids = el.getJsxChildren().filter((c) => !(Node.isJsxText(c) && c.getText().trim() === ""));
    const closeStart = el.getClosingElement().getStart();
    if (!kids.length) {
      const openEnd = el.getOpeningElement().getEnd();
      return new TsxDoc(
        applyReplacements(text, [
          {
            start: openEnd,
            end: closeStart,
            text: `\n${indent}${printNode(node, indent)}\n${parentIndent}`,
          },
        ]),
      );
    }
    const last = kids[kids.length - 1]!;
    const childIndent = lineIndent(text, kids[0]!.getStart()) || indent;
    return new TsxDoc(
      applyReplacements(text, [
        {
          start: last.getEnd(),
          end: last.getEnd(),
          text: `\n${childIndent}${printNode(node, childIndent)}`,
        },
      ]),
    );
  }

  /** Remove the element and the line it sat on. */
  remove(id: string): TsxDoc {
    const sf = this.sf();
    const { el } = this.find(sf, id);
    const text = this.text;
    let start = el.getStart();
    let end = el.getEnd();
    while (start > 0 && (text[start - 1] === " " || text[start - 1] === "\t")) start--;
    if (text[start - 1] === "\n") {
      start--;
      if (text[start - 1] === "\r") start--;
    }
    return new TsxDoc(applyReplacements(text, [{ start, end, text: "" }]));
  }

  /** Replace the element with new JSX source (used by scene_write). The new source must parse. */
  replaceElement(id: string, jsx: string): TsxDoc {
    const sf = this.sf();
    const { el } = this.find(sf, id);
    const indent = lineIndent(this.text, el.getStart());
    const body = jsx
      .trim()
      .split("\n")
      .map((l, i) => (i === 0 ? l : indent + l))
      .join("\n");
    return new TsxDoc(applyReplacements(this.text, [{ start: el.getStart(), end: el.getEnd(), text: body }]));
  }

  /** The source text of one element. */
  elementText(id: string): string {
    return this.find(this.sf(), id).el.getText();
  }

  /** Give elements that lack an id a stable one (the same ids the resolver would assign). Returns new text and what was written. */
  writeIds(tree: CCNode): { doc: TsxDoc; written: Array<{ path: string; id: string }> } {
    const copy = structuredCloneNode(tree);
    const added = assignMissingIds(copy);
    if (!added.length) return { doc: this, written: [] };
    const sf = this.sf();
    const byPath = mapPaths(sf);
    const reps: Replacement[] = [];
    const written: Array<{ path: string; id: string }> = [];
    for (const a of added) {
      const tag = byPath.get(a.path);
      if (!tag) continue;
      const end = tag.getTagNameNode().getEnd();
      reps.push({ start: end, end, text: ` id="${a.id}"` });
      written.push({ path: a.path, id: a.id });
    }
    return { doc: new TsxDoc(applyReplacements(this.text, reps)), written };
  }

  /** Add named imports for components the file does not import yet (from the module it already imports components from). */
  ensureImports(names: string[], moduleName = "@codecut/components"): TsxDoc {
    const sf = this.sf();
    const have = new Set<string>();
    for (const d of sf.getImportDeclarations())
      for (const n of d.getNamedImports()) have.add(n.getAliasNode()?.getText() ?? n.getName());
    for (const d of sf.getVariableDeclarations()) have.add(d.getName());
    for (const d of sf.getFunctions()) if (d.getName()) have.add(d.getName()!);
    const need = [...new Set(names)].filter((n) => !have.has(n));
    if (!need.length) return this;
    const decl =
      sf.getImportDeclaration((d) => /^(@codecut\/components|codecut\/components)$/.test(d.getModuleSpecifierValue())) ??
      undefined;
    if (decl) {
      const named = decl.getNamedImports();
      const last = named[named.length - 1];
      if (last) {
        const multi = decl.getStartLineNumber() !== decl.getEndLineNumber();
        const sep = multi ? `,\n${lineIndent(this.text, last.getStart())}` : ", ";
        return new TsxDoc(
          applyReplacements(this.text, [{ start: last.getEnd(), end: last.getEnd(), text: sep + need.join(sep) }]),
        );
      }
      const open = decl.getText().indexOf("{");
      if (open >= 0) {
        const at = decl.getStart() + open + 1;
        return new TsxDoc(applyReplacements(this.text, [{ start: at, end: at, text: ` ${need.join(", ")} ` }]));
      }
      return new TsxDoc(applyReplacements(this.text, [{ start: decl.getEnd(), end: decl.getEnd(), text: `\nimport { ${need.join(", ")} } from "${decl.getModuleSpecifierValue()}";` }]));
    }
    const imports = sf.getImportDeclarations();
    const line = `import { ${need.join(", ")} } from "${moduleName}";`;
    const last = imports[imports.length - 1];
    const at = last ? last.getEnd() : 0;
    return new TsxDoc(applyReplacements(this.text, [{ start: at, end: at, text: last ? "\n" + line : line + "\n" }]));
  }

  /** Throws a typed error when the text has syntax errors. */
  assertParses(): void {
    const sf = this.sf();
    const diags = project.getProgram().getSyntacticDiagnostics(sf);
    if (diags.length) {
      const d = diags[0]!;
      const msg = typeof d.getMessageText() === "string" ? (d.getMessageText() as string) : "syntax error";
      throw new CodeCutError(
        "schema_violation",
        `TSX does not parse: ${msg} (line ${d.getLineNumber() ?? "?"})`,
        { fix: "Fix the syntax and try again." },
      );
    }
  }
}

function structuredCloneNode(n: CCNode): CCNode {
  return {
    $cc: 1,
    name: n.name,
    props: { ...n.props },
    children: n.children.map((c) => (isNode(c) ? structuredCloneNode(c) : c)),
  };
}

/** Map the resolver's structural paths to JSX tags, stopping at children that cannot be mapped statically. */
function mapPaths(sf: SourceFile): Map<string, Tag> {
  const out = new Map<string, Tag>();
  const exp = sf.getExportAssignment((e) => !e.isExportEquals());
  const root = exp
    ?.getDescendants()
    .find(
      (d) =>
        (Node.isJsxElement(d) || Node.isJsxSelfClosingElement(d)) &&
        !d.getAncestors().some((a) => Node.isJsxElement(a) || Node.isJsxSelfClosingElement(a)),
    );
  if (!root) return out;
  const nameOf = (n: Node): string =>
    Node.isJsxElement(n)
      ? n.getOpeningElement().getTagNameNode().getText()
      : (n as JsxSelfClosingElement).getTagNameNode().getText();
  const tagOf = (n: Node): Tag =>
    Node.isJsxElement(n) ? n.getOpeningElement() : (n as JsxSelfClosingElement);
  const visit = (n: Node, path: string) => {
    out.set(path, tagOf(n));
    if (!Node.isJsxElement(n)) return;
    let i = 0;
    const walkKids = (kids: Node[]): boolean => {
      for (const c of kids) {
        if (Node.isJsxElement(c) || Node.isJsxSelfClosingElement(c)) {
          visit(c, `${path}/${nameOf(c)}[${i}]`);
          i++;
        } else if (Node.isJsxText(c)) {
          if (c.getText().trim() !== "") i++;
        } else if (Node.isJsxFragment(c)) {
          if (!walkKids(c.getJsxChildren())) return false;
        } else if (Node.isJsxExpression(c)) {
          const e = c.getExpression();
          if (e) return false; // opaque: later indices are unknown
        }
      }
      return true;
    };
    walkKids(n.getJsxChildren());
  };
  visit(root, nameOf(root));
  return out;
}

/** Apply core patches to source text. The shadow tree keeps sibling anchors correct across a patch list. */
export function applyPatchesToSource(text: string, patches: Patch[], tree: CCNode): string {
  let doc = new TsxDoc(text);
  let shadow = tree;
  for (const p of patches) {
    if (p.op === "setProp") {
      doc = doc.setProp(p.id, p.prop, p.value);
    } else if (p.op === "remove") {
      doc = doc.remove(p.id);
    } else {
      const parent = findById(shadow, p.parent)?.node;
      const sibs = (parent?.children ?? []).filter(isNode);
      const kids = parent?.children ?? [];
      const at = Math.max(0, Math.min(kids.length, p.index));
      const next = kids.slice(at).find(isNode) as CCNode | undefined;
      const prev = [...kids.slice(0, at)].reverse().find(isNode) as CCNode | undefined;
      void sibs;
      doc = doc.insert(p.parent, p.node, {
        before: next && typeof next.props.id === "string" ? next.props.id : undefined,
        after:
          !next && prev && typeof prev.props.id === "string" ? (prev.props.id as string) : undefined,
      });
    }
    shadow = applyPatches(shadow, [p]).project;
  }
  const names: string[] = [];
  for (const p of patches) if (p.op === "insert") collectNames(p.node, names);
  return doc.ensureImports(names).text;
}

function collectNames(n: CCNode, out: string[]): void {
  out.push(n.name);
  for (const c of n.children) if (isNode(c)) collectNames(c, out);
}
